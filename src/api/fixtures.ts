  const adv = FIXTURE_SELLER_MODELS.data.advertised.find((a) => a.model === modelId);
  const baseIn = adv?.input_usd_per_m ?? 1.5;
  const baseCached = adv?.cached_input_usd_per_m ?? baseIn * 0.1;
  const baseOut = adv?.output_usd_per_m ?? baseIn * 4;
